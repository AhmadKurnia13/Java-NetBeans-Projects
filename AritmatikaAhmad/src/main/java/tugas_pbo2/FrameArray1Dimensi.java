    private void btnTampilkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTampilkanActionPerformed
        // TODO add your handling code here:
        txtAreaHasil.setText(""); // Kosongkan layar dulu setiap kali ditekan
        txtAreaHasil.append("Daftar Nilai Array 1 Dimensi Ahmad Kurnia:\n");
        txtAreaHasil.append("=========================================\n");
        for (int i = 0; i < indexData; i++) {
            txtAreaHasil.append("Data ke-" + (i + 1) + " (Indeks " + i + ") : " + dataArray[i] + "\n");
        }
    }//GEN-LAST:event_btnTampilkanActionPerformed

