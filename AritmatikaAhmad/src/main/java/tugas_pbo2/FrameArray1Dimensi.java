    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        // TODO add your handling code here:
        try {
            int nilai = Integer.parseInt(txtNilai.getText());
            if (indexData < dataArray.length) {
                dataArray[indexData] = nilai;
                indexData++; // Geser ke indeks berikutnya
                txtNilai.setText("");
                txtNilai.requestFocus(); // Kursor kembali ke kotak isian
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Kapasitas Array sudah penuh!");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pastikan memasukkan angka bulat yang valid!");
        }
    }//GEN-LAST:event_btnTambahActionPerformed

