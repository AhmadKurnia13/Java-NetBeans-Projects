    private void cmbDollarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbDollarActionPerformed
        // TODO add your handling code here:
        // Bersihkan area teks terlebih dahulu
        txtAreaDollar.setText("");
        txtAreaRupiah.setText("");
        txtAreaYen.setText("");

// Ambil angka yang dipilih dari ComboBox
        int jumlah = Integer.parseInt(cmbDollar.getSelectedItem().toString());

// Asumsi kurs (bisa diubah sesuai ketentuan soal dosen)
        int kursRupiah = 15000;
        int kursYen = 150;

// Melakukan perulangan dari 1 sampai 'jumlah' yang dipilih
        for (int i = 1; i <= jumlah; i++) {
            txtAreaDollar.append("$ " + i + "\n");
            txtAreaRupiah.append("Rp " + (i * kursRupiah) + "\n");
            txtAreaYen.append("¥ " + (i * kursYen) + "\n");
        }
    }//GEN-LAST:event_cmbDollarActionPerformed

