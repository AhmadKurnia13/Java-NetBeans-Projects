    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        // TODO add your handling code here:
        txtIsi.setText(null);
        String p = txtPath.getText();
        File file = new File(p);

        try {
            FileInputStream fs = new FileInputStream(file);
            DataInputStream in = new DataInputStream(fs);
            BufferedReader br = new BufferedReader(new InputStreamReader(in));
            String strline;

            while ((strline = br.readLine()) != null) {
                StringTokenizer st = new StringTokenizer(strline, ",");
                txtIsi.setText(txtIsi.getText() + st.nextToken() + "\n");
            }

            in.close();
        } catch (Exception e) {
            System.out.println("Error :" + e.getMessage());
        }
    }//GEN-LAST:event_btnViewActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        File file = new File(txtPath.getText());
        if (file.exists()) {
            int confirm = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus file ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                if (file.delete()) {
                    JOptionPane.showMessageDialog(this, "File berhasil dihapus!");
                    txtPath.setText(""); // Kosongkan path
                    txtIsi.setText("");  // Kosongkan isi
                } else {
                    JOptionPane.showMessageDialog(this, "File gagal dihapus!");
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Pilih file terlebih dahulu!");
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

